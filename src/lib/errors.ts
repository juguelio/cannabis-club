export class AppError extends Error {
  status: number;
  code: string;
  details?: unknown;
  constructor(status: number, code: string, message: string, details?: unknown) {
    super(message);
    this.status = status;
    this.code = code;
    this.details = details;
  }
}

export const badRequest = (code: string, message: string, details?: unknown) =>
  new AppError(400, code, message, details);
export const unauthorized = (message = "Sesión requerida") => new AppError(401, "UNAUTHORIZED", message);
export const forbidden = (message = "No autorizado") => new AppError(403, "FORBIDDEN", message);
export const notFound = (message = "No encontrado") => new AppError(404, "NOT_FOUND", message);
export const conflict = (code: string, message: string, details?: unknown) =>
  new AppError(409, code, message, details);
export const unprocessable = (code: string, message: string, details?: unknown) =>
  new AppError(422, code, message, details);
